/**
 * WebP encoding with content hashes (D8) and the size budgets of the P4
 * acceptance: an object at most OBJECT_BUDGET bytes, a texture at most
 * TEXTURE_BUDGET. The quality steps down until the file fits.
 */

import { createHash } from "node:crypto";

import sharp from "sharp";

import type { BuiltinManifest, ManifestSprite } from "../../../src/lib/sprite-packs/manifest";
import { MANIFEST_SCHEMA_VERSION } from "../../../src/lib/sprite-packs/manifest";
import type { RgbaImage } from "../../../src/lib/sprite-packs/cut";
import type { FolderResult, Item } from "./pipeline";

export const OBJECT_BUDGET = 80 * 1024;
export const TEXTURE_BUDGET = 200 * 1024;

const OBJECT_QUALITY = 82;
const TEXTURE_QUALITY = 80;
const MIN_QUALITY = 40;

export type Encoded = {
  item: Item;
  /** Path relative to public/sprite-packs/ (`forest/oak-tree.1a2b3c4d.webp`). */
  file: string;
  bytes: Buffer;
  quality: number;
};

function raw(img: RgbaImage) {
  return sharp(Buffer.from(img.data.buffer, img.data.byteOffset, img.data.length), {
    raw: { width: img.width, height: img.height, channels: 4 },
  });
}

export async function encodeItem(item: Item): Promise<Encoded> {
  const texture = item.entry.category === "texture";
  const budget = texture ? TEXTURE_BUDGET : OBJECT_BUDGET;
  let quality = texture ? TEXTURE_QUALITY : OBJECT_QUALITY;
  for (;;) {
    const pipe = raw(item.image);
    const bytes = await (texture
      ? pipe.removeAlpha().webp({ quality, effort: 6, smartSubsample: true })
      : pipe.webp({ quality, alphaQuality: 90, effort: 6, smartSubsample: true })
    ).toBuffer();
    if (bytes.length <= budget || quality <= MIN_QUALITY) {
      if (bytes.length > budget) throw new Error(`${item.key}: ${bytes.length} bytes over the ${budget} budget at q${quality}`);
      const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 8);
      const [folder, slug] = item.key.split("/");
      const name = item.variant > 1 ? `${slug}-v${item.variant}` : slug;
      return { item, file: `${folder}/${name}.${hash}.webp`, bytes, quality };
    }
    quality -= 6;
  }
}

/** PNG of an RGBA image (review output). */
export function png(img: RgbaImage): Promise<Buffer> {
  return raw(img).png({ compressionLevel: 9 }).toBuffer();
}

/** The manifest entries of one folder, in catalog order (variants after their item's own cut). */
export function folderManifest(folder: FolderResult, encoded: ReadonlyMap<Item, Encoded>): ManifestSprite[] {
  const out: ManifestSprite[] = [];
  const byKey = new Map<string, ManifestSprite>();
  const sorted = [...folder.items].sort((a, b) => a.variant - b.variant);
  for (const item of sorted) {
    const enc = encoded.get(item);
    if (!enc) continue;
    const art = { file: enc.file, px: { w: item.image.width, h: item.image.height } };
    const existing = byKey.get(item.key);
    if (existing) {
      existing.variants.push(art);
      continue;
    }
    const sprite: ManifestSprite = {
      key: item.key,
      ...art,
      variants: [],
      ...(item.tile ? { seam: Math.round(item.tile.after * 1000) / 1000 } : {}),
    };
    byKey.set(item.key, sprite);
    out.push(sprite);
  }
  const order = new Map(folder.items.filter((i) => i.variant === 1).map((i, n) => [i.key, n]));
  return out.sort((a, b) => (order.get(a.key) ?? 0) - (order.get(b.key) ?? 0));
}

/** The generated src/lib/sprite-packs/builtin/manifest.ts. */
export function manifestSource(manifest: BuiltinManifest): string {
  const lines: string[] = [
    "/**",
    " * GENERATED by `pnpm sprites:build` (scripts/sprite-packs/build-pack.ts). Do not edit by hand:",
    " * rerun the build (docs/sprite-packs/prompts.md, Status). Files live under public/sprite-packs/ and are",
    " * content-hashed, so they are served immutable (D8). Traits come from the catalog (createSpriteLookup).",
    " */",
    "",
    'import type { BuiltinManifest } from "../manifest";',
    "",
    "export const BUILTIN_MANIFEST: BuiltinManifest = {",
    `  schemaVersion: ${MANIFEST_SCHEMA_VERSION},`,
    "  folders: {",
  ];
  for (const [folder, sprites] of Object.entries(manifest.folders)) {
    lines.push(`    ${JSON.stringify(folder)}: [`);
    // Fixed key order, so a partial rebuild (which re-reads the other folders through zod) writes identical lines.
    for (const s of sprites) {
      const canonical = {
        key: s.key,
        file: s.file,
        px: { w: s.px.w, h: s.px.h },
        variants: s.variants.map((v) => ({ file: v.file, px: { w: v.px.w, h: v.px.h } })),
        ...(s.seam !== undefined ? { seam: s.seam } : {}),
      };
      lines.push(`      ${JSON.stringify(canonical)},`);
    }
    lines.push("    ],");
  }
  lines.push("  },", "};", "");
  return lines.join("\n");
}
